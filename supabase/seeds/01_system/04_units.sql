-- ============================================================================
-- 04_units.sql — وحدات القياس
-- ============================================================================
--
-- ما هذا الملف؟
--   وحدات القياس التي يقيس بها النظام الكميات. كل منتج في النظام يحمل وحدة،
--   لذا لا يعمل النظام بدون هذه الصفوف.
--
-- لماذا هو ملف نظام (يُشغَّل تلقائيًا)؟
--   لأن الوحدات الفيزيائية ثابتة في كل العالم: الكيلوجرام كيلوجرام في أي منشأة،
--   سواء كانت مطحنة أو قرطاسية أو صيدلية. لا معنى لترك كل عميل يعرّفها بنفسه.
--
-- ── قرار مهم: الفرق بين الوحدة والعبوة ──────────────────────────────────────
--   الوحدة  : مقدار فيزيائي قياسي — كيلوجرام، لتر، متر، قطعة.
--   العبوة  : إناء يحمل كمية محدّدة — كيس 50 كجم، شوال، كرتون 24 حبة.
--
--   كانت النسخة السابقة تخلط الاثنين: كانت تحتوي «كيس 10 كجم» و«شوال 50 كجم»
--   كأنهما وحدتا قياس. وهذا خطأ من ثلاثة أوجه:
--     1. «كيس 10 كجم» ليست وحدة — إنها عبوة بوزن محدّد.
--     2. كان فيه «Sack 50 kg» و«Sack 50kg» — نفس العبوة باسمين، تُنشئ صفين.
--     3. العبوة تخصّ منشأة بعينها (مطحنة تشتري شوالات، متجر لا يشتريها).
--
--   اليوم: الوحدات الفيزيائية فقط في هذا الملف.
--   والعبوات في packaging_types (نظامية) أو في بيانات المنشأة (خاصة).
--
-- ── الرموز ──────────────────────────────────────────────────────────────────
--   short_name هو ما يظهر في الفواتير وأعمدة الطباعة والتقارير. يجب أن يكون
--   لاتينيًا قصيرًا وموحّدًا: «kg» لا «كيلوجرام»، و«pc» لا «قطعة».
--   الاسم العربي مكانه name_ar.
--
-- ثابت (Idempotent): يُشغَّل أكثر من مرة بأمان عبر ON CONFLICT على (name).
-- المرجع: supabase/docs/2026-10-12_guide_migrations-rules.md — القاعدة R-19.
-- ============================================================================

BEGIN;

INSERT INTO public.units (name, short_name, name_ar, dimension_code, factor_to_reference) VALUES
  -- ── العدّ ──────────────────────────────────────────────────────────────────
  ('Piece',       'pc',  'قطعة',       'COUNT',     1),
  ('Dozen',       'dz',  'دستة',       'COUNT',    12),
  ('Set',         'st',  'طقم',        'PACKAGING', NULL),

  -- ── الوزن ──────────────────────────────────────────────────────────────────
  ('Gram',        'g',   'جرام',       'MASS',      1),
  ('Kilogram',    'kg',  'كيلوجرام',   'MASS',   1000),
  ('Ton',         't',   'طن متري',    'MASS',1000000),

  -- ── الحجم ──────────────────────────────────────────────────────────────────
  ('Millilitre',  'ml',  'مليلتر',     'VOLUME',    1),
  ('Litre',       'L',   'لتر',        'VOLUME', 1000),

  -- ── الطول والمساحة ─────────────────────────────────────────────────────────
  ('Metre',       'm',   'متر',        'LENGTH',    1),
  ('SquareMetre', 'm2',  'متر مربع',   'AREA',       1),

  -- ── التعبئة القياسية ───────────────────────────────────────────────────────
  -- هذه أنواع تغليف عامة، لا عبوات بوزن محدّد. «صندوق» و«حزمة» و«رزمة»
  -- مفاهيم يستخدمها كل نشاط تجاري تقريبًا.
  ('Box',         'bx',  'صندوق',      'PACKAGING', NULL),
  ('Pack',        'pk',  'حزمة',       'PACKAGING', NULL),
  ('Ream',        'rm',  'رزمة ورق',   'PACKAGING', NULL)
ON CONFLICT (name) DO UPDATE
  SET dimension_code = EXCLUDED.dimension_code,
      factor_to_reference = EXCLUDED.factor_to_reference;

COMMIT;

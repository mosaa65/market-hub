-- ============================================================================
-- 05_expense_categories.sql — تصنيفات المصروفات الافتراضية
-- ============================================================================
--
-- ما هذا الملف؟
--   التصنيفات التي يبدأ بها كل عميل، **كل تصنيف مربوط بحسابه المحاسبي**.
--
-- لماذا هو ملف نظام (يُشغَّل تلقائيًا)؟
--   لأن شاشة المصروفات تشترط اختيار تصنيف قبل الحفظ. بلا هذه الصفوف يعجز
--   أي عميل جديد عن تسجيل مصروفه الأول.
--
-- ── الفرق بين التصنيف والحساب ───────────────────────────────────────────────
--   التصنيف تنظيم إداري: «كيف يصنّف المالك مصروفه في الشاشة».
--   الحساب  وجهة محاسبية: «إلى أين يذهب في الدفاتر».
--
--   وهما ليسا شيئًا واحدًا، لذلك لم يُدمجا. لكن بلا رابط بينهما، كانت عشرة
--   تصنيفات تُدفن في خمسة حسابات: فالتسويق والمواصلات والصيانة كلها في سطر
--   واحد، فيفقد المالك معرفة ما صرفه على التسويق.
--
--   اليوم: عمود account_id يربط كل تصنيف بحسابه (يُحلّ بالكود لا بالمعرّف،
--   فلا معرّفات ثابتة في الملف).
--
-- ── لماذا يمكن للمالك تغيير الربط؟ ─────────────────────────────────────────
--   لأن منشأة قد تُحمّل الإيجار على تكلفة الإنتاج وأخرى على المصروف الإداري.
--   الربط هنا **افتراضي معقول** لا قيد.
--
-- ثابت (Idempotent): ON CONFLICT على (name).
-- المرجع: supabase/MIGRATIONS_RULES.md — القاعدتان R-19 و R-30.
-- ============================================================================

BEGIN;

-- كل صف: (اسم، اسم عربي، ترتيب، كود الحساب المحاسبي)
-- الحساب يُحلّ باستعلام فرعي على الكود، فلا معرّف ثابت في الملف.
INSERT INTO public.expense_categories (name, name_ar, sort_order, is_active, account_id)
SELECT
  v.name,
  v.name_ar,
  v.sort_order,
  true,
  (SELECT id FROM public.accounts WHERE code = v.account_code)
FROM (VALUES
  ('Rent',        'إيجارات',           10, '5313'),
  ('Salaries',    'رواتب وأجور',        20, '5221'),
  ('Utilities',   'كهرباء ومياه',       30, '5311'),
  ('Transport',   'مواصلات ونقل',       40, '5315'),
  ('Maintenance', 'صيانة وإصلاح',       50, '5314'),
  ('Packaging',   'تعبئة وتغليف',       60, '5316'),
  ('Internet',    'اتصالات وإنترنت',    70, '5312'),
  ('Office',      'مصروفات مكتبية',     80, '5317'),
  ('Marketing',   'تسويق وإعلان',       90, '5318'),
  ('Professional','أتعاب مهنية',       100, '5319'),
  ('Other',       'مصروفات أخرى',      110, '5911')
) AS v(name, name_ar, sort_order, account_code)
ON CONFLICT (name) DO NOTHING;

-- ── التحقق: كل تصنيف يجب أن يكون له حساب ────────────────────────────────
-- تصنيف بلا حساب يعني مصروفًا يقع على الحساب الافتراضي بلا اختيار المالك،
-- ولا يكتشف ذلك إلا بعد أن تختل التقارير. نكشفه هنا قبل أن يحدث.
DO $$
DECLARE
  v_orphans text[];
BEGIN
  SELECT array_agg(c.name) INTO v_orphans
    FROM public.expense_categories c
   WHERE c.is_active AND c.account_id IS NULL;

  IF v_orphans IS NOT NULL THEN
    RAISE EXCEPTION
      'تصنيفات مصروف بلا حساب محاسبي مربوط: %',
      array_to_string(v_orphans, ', ');
  END IF;
END $$;

COMMIT;

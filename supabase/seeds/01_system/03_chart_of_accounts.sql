-- ── التحقق بعد الإدخال ──────────────────────────────────────────────────
-- نتأكد أن كل كود يستخدمه محرّك الترحيل موجود فعلًا. لو نقص حساب، يفشل الترحيل
-- لاحقًا برسالة غامضة «account code does not exist»، وهنا تظهر المشكلة قبل حدوثها.
--
-- القائمة أدناه **مستخرجة من ملفات الترحيل**: كل كود مكتوب كنص داخل دالة.
-- إن أضفت حسابًا يستخدمه كود الترحيل، أضف كوده هنا.
DO $$
DECLARE
  v_required text[] := ARRAY[
    -- النقدية والبنوك — post_sales_invoice / post_purchase_invoice
    '1101','1111',
    -- ذمم العملاء — post_sales_invoice
    '1211',
    -- المخزون وضريبة المدخلات — الترحيل ومحرك التكلفة والإنتاج
    '1311','1312','1313','1314','1315','1316',
    -- ذمم الموردين — post_purchase_invoice
    '2111',
    -- ضريبة المخرجات — post_sales_invoice
    '2311',
    -- رأس المال — post_opening_balance
    '3111',
    -- الإيرادات — post_sales_invoice يوزّعها حسب item_class
    '4111','4211','4311',
    -- تكلفة المبيعات — post_sales_invoice
    '5111',
    -- العمالة والطاقة — post_production_order
    '5211','5311',
    -- مصروفات متنوعة — الترحيل والتسويات
    '5911'
  ];
  v_missing text[];
BEGIN
  SELECT array_agg(c) INTO v_missing
    FROM unnest(v_required) AS c
   WHERE NOT EXISTS (SELECT 1 FROM public.accounts a WHERE a.code = c);

  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION
      'حساب محاسبي مطلوب لم يُدرَج، وسيفشل الترحيل بدونه: %',
      array_to_string(v_missing, ', ');
  END IF;
END $$;


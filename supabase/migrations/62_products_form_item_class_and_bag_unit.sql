-- على مستوى النظام (tenant_id IS NULL) مثل باقي الوحدات الفيزيائية.
INSERT INTO public.units (name, short_name, name_ar)
SELECT 'Bag', 'bag', 'كيس'
WHERE NOT EXISTS (
  SELECT 1 FROM public.units WHERE name = 'Bag'
);
